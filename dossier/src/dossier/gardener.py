"""Gardener — consolidation + lint pass.

Fuses HMLR's gardener (promote bridge blocks to long-term, walk supersession
chains) with Karpathy's lint operation (orphans, stale claims, missing
cross-references, regenerate index).

One nightly (or on-trigger) process, not two. See SCHEMA.md for the
contradiction-resolution policy it enforces.
"""

from __future__ import annotations

import datetime as _dt
import re
from collections import defaultdict
from dataclasses import dataclass, field
from pathlib import Path

from dossier import frontmatter as fm
from dossier.config import DossierConfig
from dossier.wiki_writer import _atomic_write

_WIKILINK_RE = re.compile(r"\[\[([^\]]+)\]\]")


@dataclass
class LintReport:
    orphans: list[str] = field(default_factory=list)
    stale: list[str] = field(default_factory=list)
    review_flagged: list[str] = field(default_factory=list)
    missing_cross_refs: list[tuple[str, str]] = field(default_factory=list)
    index_regenerated: bool = False

    def summary(self) -> str:
        return (
            f"orphans={len(self.orphans)} stale={len(self.stale)} "
            f"review={len(self.review_flagged)} missing_xref={len(self.missing_cross_refs)}"
        )


class Gardener:
    def __init__(self, cfg: DossierConfig):
        self._cfg = cfg

    def run(self) -> LintReport:
        self._cfg.ensure_dirs()
        pages = _collect_pages(self._cfg.wiki_dir)
        report = LintReport()
        self._find_orphans(pages, report)
        self._find_stale(pages, report)
        self._find_review_flags(pages, report)
        self._find_missing_cross_refs(pages, report)
        self._regenerate_index(pages)
        report.index_regenerated = True
        self._append_log(report)
        return report

    # --- lint rules --------------------------------------------------------

    def _find_orphans(self, pages: dict[str, fm.Page], report: LintReport) -> None:
        referenced: set[str] = set()
        for rel, page in pages.items():
            for match in _WIKILINK_RE.finditer(page.body):
                referenced.add(_normalise_ref(match.group(1)))
        for rel in pages:
            ref = _normalise_ref(rel.removesuffix(".md"))
            if ref not in referenced:
                report.orphans.append(rel)

    def _find_stale(self, pages: dict[str, fm.Page], report: LintReport) -> None:
        today = _dt.date.today()
        threshold = _dt.timedelta(days=self._cfg.confidence_stale_threshold_days)
        for rel, page in pages.items():
            if page.confidence != "low":
                continue
            if today - page.last_updated > threshold:
                report.stale.append(rel)

    def _find_review_flags(self, pages: dict[str, fm.Page], report: LintReport) -> None:
        for rel, page in pages.items():
            if "[[REVIEW]]" in page.body:
                report.review_flagged.append(rel)

    def _find_missing_cross_refs(self, pages: dict[str, fm.Page], report: LintReport) -> None:
        # if page A mentions page B's name literally but doesn't wiki-link to B, flag it.
        names_to_rel: dict[str, str] = {}
        for rel, page in pages.items():
            names_to_rel[page.name.lower()] = rel.removesuffix(".md")
            for alias in page.aliases:
                names_to_rel[alias.lower()] = rel.removesuffix(".md")

        for rel, page in pages.items():
            body_lower = page.body.lower()
            already_linked = {_normalise_ref(m.group(1)) for m in _WIKILINK_RE.finditer(page.body)}
            for name, target_ref in names_to_rel.items():
                target_norm = _normalise_ref(target_ref)
                # don't flag self-references, and skip if already linked
                if target_ref == rel.removesuffix(".md") or target_norm in already_linked:
                    continue
                if name in body_lower and len(name) > 3:
                    report.missing_cross_refs.append((rel, target_ref))

    # --- index regen -------------------------------------------------------

    def _regenerate_index(self, pages: dict[str, fm.Page]) -> None:
        buckets: dict[str, list[tuple[str, fm.Page]]] = defaultdict(list)
        for rel, page in pages.items():
            if page.kind in ("index", "log"):
                continue
            buckets[page.kind].append((rel, page))
        for kind in buckets:
            buckets[kind].sort(key=lambda pair: pair[1].name.lower())

        today = _dt.date.today().isoformat()
        lines = [
            "---",
            "kind: index",
            f"last_updated: {today}",
            "regenerated_by: gardener",
            "---",
            "",
            "# Wiki index",
            "",
            "This index is auto-regenerated by `dossier gardener`.",
            "",
        ]
        for kind, title in (("entity", "Entities"), ("concept", "Concepts"), ("source", "Sources")):
            lines += [f"## {title}", ""]
            rows = buckets.get(kind, [])
            if not rows:
                lines.append("_(empty)_")
            else:
                for rel, page in rows:
                    stem = rel.removesuffix(".md")
                    lines.append(f"- [[{stem}]] — {page.name} (confidence: {page.confidence})")
            lines.append("")
        index_path = self._cfg.wiki_dir / "index.md"
        _atomic_write(index_path, "\n".join(lines))

    def _append_log(self, report: LintReport) -> None:
        log_path = self._cfg.wiki_dir / "log.md"
        today = _dt.date.today().isoformat()
        existing = log_path.read_text(encoding="utf-8") if log_path.exists() else ""
        heading = f"## {today}"
        entry = f"- **gardener pass** — {report.summary()}"
        if heading in existing:
            patched = re.sub(
                rf"({re.escape(heading)}\n)",
                rf"\1\n{entry}\n",
                existing,
                count=1,
            )
        else:
            if not existing:
                existing = f"---\nkind: log\nlast_updated: {today}\n---\n\n# Activity log\n\n"
            fm_end = existing.find("---", 3)
            insert_at = existing.find("\n", fm_end) + 1 if fm_end != -1 else 0
            patched = (
                existing[:insert_at]
                + f"\n{heading}\n\n{entry}\n"
                + existing[insert_at:]
            )
        _atomic_write(log_path, patched)


def _collect_pages(wiki_dir: Path) -> dict[str, fm.Page]:
    out: dict[str, fm.Page] = {}
    for sub in ("entities", "concepts", "sources"):
        d = wiki_dir / sub
        if not d.exists():
            continue
        for path in sorted(d.glob("*.md")):
            try:
                page = fm.loads(path.read_text(encoding="utf-8"))
            except fm.FrontmatterError:
                continue
            rel = path.relative_to(wiki_dir).as_posix()
            out[rel] = page
    return out


def _normalise_ref(ref: str) -> str:
    return ref.strip().lower().replace("\\", "/")
